package ai

import (
	"context"
	"fmt"
	"net/http"
	"strings"

	"github.com/danielgtaylor/huma/v2"
	"github.com/kiwit/kiwit/internal/auth"
	"github.com/kiwit/kiwit/internal/llm"
	"github.com/kiwit/kiwit/internal/requirement"
	"github.com/kiwit/kiwit/internal/testcase"
)

type GeneratedCase struct {
	ID      int64  `json:"id"`
	Summary string `json:"summary"`
}

type generateOutput struct {
	Body struct {
		Created   []GeneratedCase `json:"created"`
		Gherkin   string          `json:"gherkin"`
		Model     string          `json:"model"`
		Scenarios int             `json:"scenarios"`
	}
}

// RegisterRoutes mounts the AI test-generation endpoint.
// POST /api/v1/ai/generate-tests — LLM writes Gherkin from a requirement,
// scenarios become draft gherkin test cases linked to the requirement.
func RegisterRoutes(api huma.API, servers *llm.ServerStore, tcRepo testcase.Repository, reqStore *requirement.Store, guard *auth.AccessGuard) {
	huma.Register(api, huma.Operation{
		OperationID: "ai-generate-tests",
		Method:      http.MethodPost,
		Path:        "/api/v1/ai/generate-tests",
		Summary:     "Generate draft Gherkin test cases from a requirement using an LLM (KIWIT_LLM_API_KEY)",
		Tags:        []string{"AI"},
	}, func(ctx context.Context, input *struct {
		Body struct {
			ProductID     int64  `json:"product_id"`
			RequirementID int64  `json:"requirement_id,omitempty" doc:"Use this requirement's text as input and link results"`
			Text          string `json:"text,omitempty" doc:"Free-form requirement text (used when requirement_id is 0)"`
			MaxScenarios  int    `json:"max_scenarios,omitempty" default:"5"`
			ServerID      int64  `json:"server_id,omitempty" doc:"AI server to use (0 = default)"`
		}
	}) (*generateOutput, error) {
		if err := auth.CheckWriteRole(ctx, "admin", "tester"); err != nil {
			return nil, err
		}
		cfg, serverName, err := resolve(ctx, servers, input.Body.ServerID)
		if err != nil {
			return nil, err
		}
		if err := guard.EnforceProduct(ctx, input.Body.ProductID, true); err != nil {
			return nil, err
		}
		var text string
		var reqID int64
		if input.Body.RequirementID != 0 {
			if err := guard.EnforceRequirement(ctx, input.Body.RequirementID, true); err != nil {
				return nil, err
			}
			r, err := reqStore.Get(ctx, input.Body.RequirementID)
			if err != nil {
				return nil, huma.Error404NotFound("requirement not found")
			}
			text = fmt.Sprintf("%s (%s)\n%s", r.Key, r.Name, r.Description)
			reqID = r.ID
		} else {
			text = input.Body.Text
		}
		if strings.TrimSpace(text) == "" {
			return nil, huma.Error400BadRequest("text or requirement_id required")
		}
		max := input.Body.MaxScenarios
		if max <= 0 || max > 10 {
			max = 5
		}
		user := llm.GeneratePrompt(text) + fmt.Sprintf("\n\nMaximum %d scenarios.", max)
		raw, err := cfg.Chat(ctx, llm.SystemPrompt(), user)
		if err != nil {
			return nil, huma.Error502BadGateway(err.Error())
		}
		gherkin := llm.ExtractGherkin(raw)
		scenarios, err := llm.ParseScenarios(gherkin)
		if err != nil {
			return nil, huma.Error502BadGateway("LLM output could not be parsed: " + err.Error())
		}
		if len(scenarios) > max {
			scenarios = scenarios[:max]
		}
		var authorID *int64
		if u, ok := auth.UserFromContext(ctx); ok {
			authorID = &u.ID
		}
		created := []GeneratedCase{}
		for _, sc := range scenarios {
			summary := sc.Name
			if len(summary) > 240 {
				summary = summary[:240]
			}
			tc, err := tcRepo.Create(ctx, testcase.UpsertParams{
				ProductID:   input.Body.ProductID,
				AuthorID:    authorID,
				Summary:     "[AI] " + summary,
				Notes:       "Generated by LLM from requirement. Review before use.",
				Format:      "gherkin",
				GherkinBody: llm.ScenarioToGherkinBody(sc),
				Priority:    "medium",
				Status:      "draft",
			})
			if err != nil {
				return nil, huma.Error500InternalServerError(fmt.Sprintf("failed to create test case for scenario %q", sc.Name), err)
			}
			if reqID != 0 {
				if err := reqStore.LinkCase(ctx, reqID, tc.ID); err != nil {
					return nil, huma.Error500InternalServerError("failed to link coverage", err)
				}
			}
			created = append(created, GeneratedCase{ID: tc.ID, Summary: tc.Summary})
		}
		out := &generateOutput{}
		out.Body.Created = created
		out.Body.Gherkin = gherkin
		out.Body.Model = cfg.Model + " (" + serverName + ")"
		out.Body.Scenarios = len(created)
		return out, nil
	})
}
